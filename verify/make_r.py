#!/usr/bin/env python3
"""Generate the compile-time R class from the real res/ directory.

There used to be a hand-maintained verify/R.java. It drifted: it was
missing the Frida strings that the GUI had been using, which is exactly
the kind of thing the typecheck exists to catch. A generated file cannot
drift, so this generates it from res/ on every run.

The generated class holds every resource the app declares, not just the
ones the sources happen to mention, so a reference to a resource that
does not exist fails the compile rather than the run.

Usage: make_r.py <res-dir> <out.java>
"""
import glob
import os
import re
import sys
import xml.dom.minidom as minidom


def value_names(path, tag):
    """Names of <tag name="..."> elements in a values XML file."""
    names = []
    if not os.path.isfile(path):
        return names
    doc = minidom.parse(path)
    for node in doc.getElementsByTagName(tag):
        if node.hasAttribute("name"):
            names.append(node.getAttribute("name"))
    return names


def file_names(directory, suffix):
    """Resource file names, without the extension."""
    if not os.path.isdir(directory):
        return []
    out = []
    for path in sorted(glob.glob(os.path.join(directory, "*" + suffix))):
        out.append(os.path.splitext(os.path.basename(path))[0])
    return out


def ids_in_layouts(directory):
    """Every @+id/ declared across the layouts."""
    ids = []
    if not os.path.isdir(directory):
        return ids
    for path in sorted(glob.glob(os.path.join(directory, "*.xml"))):
        body = open(path, encoding="utf-8").read()
        for m in re.finditer(r'android:id="@\+id/([\w.]+)"', body):
            ids.append(m.group(1))
    return ids


def ids_in_res(res):
    """Every @+id/ declared anywhere in res/.

    Menu items live in res/menu, not in a layout, and a missing one
    shows up as an unresolved R.id at compile time.
    """
    ids = []
    for path in sorted(glob.glob(os.path.join(res, "**", "*.xml"), recursive=True)):
        body = open(path, encoding="utf-8").read()
        for m in re.finditer(r'android:id="@\+id/([\w.]+)"', body):
            ids.append(m.group(1))
    return ids


def unique(values):
    """Order-preserving de-duplication."""
    seen = set()
    out = []
    for value in values:
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out


def java_name(name):
    """Turn a resource name into a valid Java identifier.

    Android maps the dots in a style name to underscores, so
    "Theme.BugDeck" is R.style.Theme_BugDeck. Anything else that is
    not a valid identifier is skipped rather than emitted broken.
    """
    ident = name.replace(".", "_")
    if not ident or not (ident[0].isalpha() or ident[0] == "_"):
        return None
    if not all(ch.isalnum() or ch == "_" for ch in ident):
        return None
    return ident


def ident_list(names):
    """De-duplicate and convert a list of resource names."""
    out = []
    for name in unique(names):
        ident = java_name(name)
        if ident and ident not in out:
            out.append(ident)
    return out


def emit(classes, out_path, package):
    """Write the R class."""
    lines = [
        "package %s;" % package,
        "",
        "/**",
        " * Generated by verify/make_r.py from the res/ directory.",
        " * Do not edit: regenerate it instead.",
        " */",
        "public final class R {",
        "    private R() {}",
    ]
    value = 0x7f010000
    for name, entries in classes:
        lines.append("")
        lines.append("    public static final class %s {" % name)
        for entry in entries:
            value += 1
            lines.append("        public static final int %s = 0x%08x;"
                         % (entry, value))
        lines.append("    }")
    lines.append("}")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    if len(sys.argv) != 3:
        print("usage: make_r.py <res-dir> <out.java>", file=sys.stderr)
        return 2
    res, out_path = sys.argv[1], sys.argv[2]

    layouts = os.path.join(res, "layout")
    values = os.path.join(res, "values")
    drawable = os.path.join(res, "drawable")
    mipmap = os.path.join(res, "mipmap")
    menu = os.path.join(res, "menu")
    xml = os.path.join(res, "xml")

    strings = value_names(os.path.join(values, "strings.xml"), "string")
    plurals = value_names(os.path.join(values, "strings.xml"), "plurals")
    strings += plurals
    colors = value_names(os.path.join(values, "colors.xml"), "color")
    # Only <style> elements are styles. A theme's <item> entries are
    # attributes, not styles, and putting them here would invent names
    # that R.style does not have.
    styles = value_names(os.path.join(values, "themes.xml"), "style")

    classes = [
        ("string", ident_list(strings)),
        ("id", ident_list(ids_in_res(res))),
        ("layout", ident_list(file_names(layouts, ".xml"))),
        ("menu", ident_list(file_names(menu, ".xml"))),
        ("color", ident_list(colors)),
        ("style", ident_list(styles)),
        ("drawable", ident_list(file_names(drawable, ".xml")
                                + file_names(drawable, ".png")
                                + file_names(drawable, ".webp")
                                + file_names(drawable, ".jpg"))),
        ("mipmap", ident_list(file_names(mipmap, ".png")
                              + file_names(mipmap, ".webp")
                              + file_names(mipmap, ".xml"))),
        ("xml", ident_list(file_names(xml, ".xml"))),
    ]

    emit(classes, out_path, "com.bugtraqapps.bugdeck")
    total = sum(len(entries) for _, entries in classes)
    print("R.java generated: %d resources" % total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
